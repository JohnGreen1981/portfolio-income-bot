"""Одноразовый скрипт: создаёт сводные листы по месяцам в Google Sheets."""
from sheets import SheetsClient

CATEGORIES = [
    "Продукты", "Овощи и фрукты", "Мясо и рыба",
    "Бытовая химия", "Аптека", "Медицина",
    "Алкоголь", "Табак", "Напитки",
    "Кафе/рестораны", "Транспорт", "Одежда и обувь",
    "Электроника", "Товары для дома", "Дом/ЖКХ",
    "Связь/интернет", "Подписки",
    "Развлечения", "Красота/уход", "Образование",
    "Семья/дети", "Долги", "Налоги", "Прочее",
]

if __name__ == "__main__":
    client = SheetsClient()
    months = list(range(4, 13))  # апрель–декабрь
    print(f"Создаю {len(months)} листов за 2026...")
    client.create_monthly_summaries(year=2026, months=months, categories=CATEGORIES)
    print("Готово!")
